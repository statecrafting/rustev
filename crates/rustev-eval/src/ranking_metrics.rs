/// The discount of condensed position `i`, 1 to 100.
pub fn discount(i: usize) -> f64 {
    f64::from_bits(DISCOUNTS[i - 1])
}

/// How a grade becomes a gain (3.4.3).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Gain {
    /// `g`.
    Linear,
    /// `2^g - 1`.
    Exponential,
}

impl Gain {
    /// An exact integer converted to binary64 for every grade 0 to 10
    /// (3.4.3). Total over `u8`: `2^g` is a power of two, exact in
    /// binary64 for any `u8`, so a grade outside 3.3.1's bound gives a
    /// finite gain, never a panic.
    pub fn of(self, grade: u8) -> f64 {
        match self {
            Gain::Linear => f64::from(grade),
            Gain::Exponential => 2f64.powi(i32::from(grade)) - 1.0,
        }
    }
}

/// A ranking metric specification (3.4.2): `precision@k`, `recall@k`,
/// `ndcg@k`, `hit@k`, `mrr` or `mrr@k`, with k from 1 to 100.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum RankingMetric {
    Precision(u64),
    Recall(u64),
    Ndcg(u64),
    Hit(u64),
    Mrr,
    MrrAt(u64),
}

impl RankingMetric {
    pub fn parse(s: &str) -> Option<RankingMetric> {
        if s == "mrr" {
            return Some(RankingMetric::Mrr);
        }
        let (name, k) = s.split_once('@')?;
        // Canonical digits only: no sign, no leading zero.
        if k.is_empty() || k.starts_with('0') || !k.bytes().all(|b| b.is_ascii_digit()) {
            return None;
        }
        let k: u64 = k.parse().ok()?;
        if !(1..=MAX_K).contains(&k) {
            return None;
        }
        Some(match name {
            "precision" => RankingMetric::Precision(k),
            "recall" => RankingMetric::Recall(k),
            "ndcg" => RankingMetric::Ndcg(k),
            "hit" => RankingMetric::Hit(k),
            "mrr" => RankingMetric::MrrAt(k),
            _ => return None,
        })
    }

    pub fn name(self) -> String {
        match self {
            RankingMetric::Precision(k) => format!("precision@{k}"),
            RankingMetric::Recall(k) => format!("recall@{k}"),
            RankingMetric::Ndcg(k) => format!("ndcg@{k}"),
            RankingMetric::Hit(k) => format!("hit@{k}"),
            RankingMetric::Mrr => "mrr".into(),
            RankingMetric::MrrAt(k) => format!("mrr@{k}"),
        }
    }

    /// The cutoff; none for `mrr`, which reads the whole list.
    pub fn k(self) -> Option<u64> {
        match self {
            RankingMetric::Precision(k)
            | RankingMetric::Recall(k)
            | RankingMetric::Ndcg(k)
            | RankingMetric::Hit(k)
            | RankingMetric::MrrAt(k) => Some(k),
            RankingMetric::Mrr => None,
        }
    }
}

impl Serialize for RankingMetric {
    fn serialize<S: serde::Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_str(&self.name())
    }
}

impl<'de> Deserialize<'de> for RankingMetric {
    fn deserialize<D: serde::Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        let s = String::deserialize(d)?;
        RankingMetric::parse(&s)
            .ok_or_else(|| serde::de::Error::custom("a ranking metric is precision@k, recall@k, ndcg@k, hit@k, mrr or mrr@k, k 1 to 100"))
    }
}

/// One entry of a ranked list: its id, and its origin when the list is a
/// `Selection` of spec 039.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Ranked {
    pub id: String,
    pub origin: Option<SelectionOrigin>,
}

/// A proposal's ranked list, in position order (3.4.2).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RankedList {
    pub entries: Vec<Ranked>,
    /// Whether the list records a per-position origin (a `Selection`).
    pub has_origin: bool,
}

/// The ranked list of a proposal parameter (3.4.2): a `Ranking`, a
/// `Shortlist` or a `Selection`. Any other value, or none, is
/// `not_a_ranking`; a list naming one id twice is `invalid_ranking`.
pub fn ranked_list(param: Option<&OutValue>) -> Result<RankedList, &'static str> {
    let (entries, has_origin): (Vec<Ranked>, bool) = match param {
        Some(OutValue::Ranking(r)) => (
            r.entries
                .iter()
                .map(|e| Ranked {
                    id: e.candidate.clone(),
                    origin: None,
                })
                .collect(),
            false,
        ),
        Some(OutValue::Shortlist(s)) => (
            s.ids
                .iter()
                .map(|id| Ranked {
                    id: id.clone(),
                    origin: None,
                })
                .collect(),
            false,
        ),
        // A shortfall adds no entry; it shows in `short@k`.
        Some(OutValue::Selection(s)) => (
            s.entries
                .iter()
                .map(|e| Ranked {
                    id: e.id.clone(),
                    origin: Some(e.origin),
                })
                .collect(),
            true,
        ),
        _ => return Err(reason::NOT_A_RANKING),
    };
    let mut seen = BTreeSet::new();
    if !entries.iter().all(|e| seen.insert(e.id.as_str())) {
        return Err(reason::INVALID_RANKING);
    }
    Ok(RankedList {
        entries,
        has_origin,
    })
}

/// One case's result for one ranking metric.
#[derive(Debug, Clone, PartialEq)]
pub struct RankingCase {
    /// The case's measure, or the reason it is excluded.
    pub outcome: Result<CaseMeasure, &'static str>,
    /// Unjudged items removed from the list the metric read; counted even
    /// when the case is excluded.
    pub unjudged_items: u64,
}

/// What a ranking declaration fixes for every case (3.4.2).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Relevance {
    pub relevant_at_least: u8,
    pub gain: Gain,
}

fn mean(value: f64) -> CaseMeasure {
    CaseMeasure::Mean { num: value, den: 1 }
}

fn excluded(reason: &'static str, unjudged_items: u64) -> RankingCase {
    RankingCase {
        outcome: Err(reason),
        unjudged_items,
    }
}

/// One case's contribution to `metric` (3.4.3). `gold` is the case's gold
/// `relevance` map; none excludes the case (`no_gold`).
pub fn ranking_case(
    metric: RankingMetric,
    list: &RankedList,
    gold: Option<&BTreeMap<String, u8>>,
    rel: Relevance,
) -> RankingCase {
    let Some(gold) = gold else {
        return excluded(reason::NO_GOLD, 0);
    };
    let read = match metric.k() {
        Some(k) => list
            .entries
            .len()
            .min(usize::try_from(k).unwrap_or(usize::MAX)),
        None => list.entries.len(),
    };
    // The condensed list: judged items in order, renumbered from 1.
    let condensed: Vec<u8> = list.entries[..read]
        .iter()
        .filter_map(|e| gold.get(&e.id).copied())
        .collect();
    let unjudged = (read - condensed.len()) as u64;
    let relevant_total = gold
        .values()
        .filter(|g| **g >= rel.relevant_at_least)
        .count() as u64;
    let relevant = |g: &u8| *g >= rel.relevant_at_least;
    if !matches!(metric, RankingMetric::Precision(_)) && relevant_total == 0 {
        return excluded(reason::NO_RELEVANT, unjudged);
    }
    if condensed.is_empty() {
        return excluded(reason::NO_JUDGED_ITEMS, unjudged);
    }
    let hits = condensed.iter().filter(|g| relevant(g)).count() as u64;
    let first = condensed.iter().position(relevant);
    let outcome = match metric {
        RankingMetric::Precision(_) => mean(hits as f64 / condensed.len() as f64),
        RankingMetric::Recall(_) => mean(hits as f64 / relevant_total as f64),
        RankingMetric::Hit(_) => CaseMeasure::Count {
            num: u64::from(hits > 0),
            den: 1,
        },
        RankingMetric::Mrr | RankingMetric::MrrAt(_) => {
            mean(first.map_or(0.0, |r| 1.0 / (r as u64 + 1) as f64))
        }
        RankingMetric::Ndcg(k) => {
            let mut dcg = 0.0;
            for (i, g) in condensed.iter().enumerate() {
                dcg += rel.gain.of(*g) * discount(i + 1);
            }
            let mut ideal: Vec<u8> = gold.values().copied().collect();
            ideal.sort_unstable_by(|a, b| b.cmp(a));
            let mut idcg = 0.0;
            for (i, g) in ideal
                .iter()
                .take(usize::try_from(k).unwrap_or(usize::MAX))
                .enumerate()
            {
                idcg += rel.gain.of(*g) * discount(i + 1);
            }
            // 3.4.3: R > 0 implies IDCG > 0 when relevant_at_least is at
            // least 1, as every declared ranking's is (3.4.2). A caller
            // passing 0 gets the exclusion, never a NaN.
            if idcg <= 0.0 {
                return excluded(reason::NO_RELEVANT, unjudged);
            }
            mean(dcg / idcg)
        }
    };
    RankingCase {
        outcome: Ok(outcome),
        unjudged_items: unjudged,
    }
}

/// One case's contribution to `short@k` (3.4.3): whether its list has
/// fewer than k entries, over the cases with a ranking.
pub fn short_case(list: &RankedList, k: u64) -> CaseMeasure {
    CaseMeasure::Count {
        num: u64::from((list.entries.len() as u64) < k),
        den: 1,
    }
}

/// One case's contribution to `backfill@p<p>` (3.4.4): whether the entry
/// at position p came from backfill, over the lists that have a position
/// p. A list without per-position origin is `no_origin`.
pub fn backfill_case(list: &RankedList, p: u64) -> Result<CaseMeasure, &'static str> {
    if !list.has_origin {
        return Err(reason::NO_ORIGIN);
    }
    // Positions count from 1: position 0 is no position of any list.
    let entry = p
        .checked_sub(1)
        .and_then(|i| usize::try_from(i).ok())
        .and_then(|i| list.entries.get(i))
        .ok_or(reason::NO_POSITION)?;
    Ok(CaseMeasure::Count {
        num: u64::from(entry.origin == Some(SelectionOrigin::Backfill)),
        den: 1,
    })
}
