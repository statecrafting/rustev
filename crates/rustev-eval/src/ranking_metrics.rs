//! Ranking measures (spec 041, 3.4.2 to 3.4.4 and 3.11).
//!
//! One case's contribution to each ranking metric, from the ranked list a
//! proposal carries and the case's gold relevance. Unjudged items are
//! removed from the top k (the condensed list) and counted, never read as
//! non-relevant; a short list is not padded; a case a metric cannot
//! measure is excluded with its reason, never scored 0 (I-2).
//!
//! Values use integer arithmetic, binary64 addition, multiplication and
//! division in the stated order, and the committed discount table, so they
//! are bit-identical on every target (I-4). Nothing here reads a clock or
//! performs I/O.

use std::collections::{BTreeMap, BTreeSet};

use rustev_contract::judgment::OutValue;
use rustev_contract::ranking_result::SelectionOrigin;
use serde::{Deserialize, Serialize};

use crate::eval_cases::CaseMeasure;

/// The largest cutoff a ranking metric declares (3.4.2).
pub const MAX_K: u64 = 100;

/// Exclusion reasons of 3.3 and 3.4, as the detail breakdown names them.
pub mod reason {
    pub const NO_GOLD: &str = "no_gold";
    pub const NOT_A_RANKING: &str = "not_a_ranking";
    pub const INVALID_RANKING: &str = "invalid_ranking";
    pub const NO_JUDGED_ITEMS: &str = "no_judged_items";
    pub const NO_RELEVANT: &str = "no_relevant";
    pub const NO_ORIGIN: &str = "no_origin";
    /// A list without position p is outside `backfill@p<p>`'s denominator.
    pub const NO_POSITION: &str = "no_position";
    /// Items, not cases: removed from a condensed list.
    pub const UNJUDGED_ITEMS: &str = "unjudged_items";
}

