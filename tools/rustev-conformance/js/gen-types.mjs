// Spec 027, 3.2.3 and 3.2.4: the document declarations, generated offline
// from the committed JSON Schemas by one exact-pinned generator, and
// committed byte-identical in both packages. `--check` regenerates and fails
// when a committed copy differs, or when the two packages' copies differ.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const schemas = join(root, 'crates/rustev-contract/schema');
const targets = [
  'integrations/rustev-wasm/types/rustev-documents.d.ts',
  'integrations/rustev-node/types/rustev-documents.d.ts',
];

const banner = `// Generated by tools/rustev-conformance/js/gen-types.mjs from
// crates/rustev-contract/schema/ (spec 027, 3.2.3). Do not edit: change the
// contract, regenerate the schemas, then regenerate this file.
//
// The types state what each document's bounded parser accepts (3.2.2); a
// field's description can state a rule the compiler enforces beyond that
// (a party the parser accepts but a definition may not name, for example).
// A document of these types can still be refused by \`compile\`.
`;

/** The type name of one schema file: rustev.plan-3.schema.json -> RustevPlan3. */
function typeName(file) {
  return file
    .replace(/\.schema\.json$/, '')
    .split(/[.\-]/)
    .filter(Boolean)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');
}

// A property that references a type and describes itself (`$ref` beside
// `description`) keeps its own description: the generator otherwise takes
// whichever description the referenced type was first resolved with, so a
// field's rule (`AddressOverride.to`: never `caller`) could show the
// referenced type's text instead. Wrapping the reference in `allOf` keeps
// the type and the field's own text.
function ownDescriptions(node) {
  if (Array.isArray(node)) return node.map(ownDescriptions);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) out[k] = ownDescriptions(v);
  if (typeof out.$ref === 'string' && typeof out.description === 'string') {
    const { $ref, ...rest } = out;
    return { ...rest, allOf: [{ $ref }] };
  }
  return out;
}

// A member schema that constrains nothing (only `description`, `title` or
// `$comment`, as a snapshot entry's `value` does: it is decoded against the
// input's declared type, which the schema cannot know) admits any JSON value.
// The generator would otherwise type it as an open object; `tsType` keeps it
// `unknown`, which is what the parser accepts.
const annotationOnly = new Set(['description', 'title', '$comment']);
function anyValue(node) {
  if (Array.isArray(node)) return node.map(anyValue);
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === 'properties' && v && typeof v === 'object' && !Array.isArray(v)) {
      out[k] = Object.fromEntries(
        Object.entries(v).map(([name, member]) => [
          name,
          member && typeof member === 'object' && !Array.isArray(member) &&
          Object.keys(member).every((key) => annotationOnly.has(key))
            ? { ...member, tsType: 'unknown' }
            : anyValue(member),
        ]),
      );
    } else {
      out[k] = anyValue(v);
    }
  }
  return out;
}

async function generate() {
  const files = readdirSync(schemas)
    .filter((f) => f.endsWith('.schema.json'))
    .sort();
  let out = banner;
  for (const f of files) {
    const schema = anyValue(ownDescriptions(JSON.parse(readFileSync(join(schemas, f), 'utf8'))));
    const name = typeName(f);
    schema.title = name;
    const ts = await compile(schema, name, {
      bannerComment: '',
      additionalProperties: false,
      strictIndexSignatures: true,
      unknownAny: true,
      format: true,
      declareExternallyReferenced: true,
    });
    // Each schema's definitions are its own: wrap it in a namespace so
    // shared names (`Decimal`, `Unresolved`) never collide.
    const body = ts
      .trim()
      .split('\n')
      .map((l) => (l ? `  ${l}` : l))
      .join('\n');
    out += `\nexport namespace ${name} {\n${body}\n}\nexport type ${name} = ${name}.${name};\n`;
  }
  return out;
}

const text = await generate();
const check = process.argv.includes('--check');
let failed = false;
for (const t of targets) {
  const p = join(root, t);
  if (check) {
    const got = existsSync(p) ? readFileSync(p, 'utf8') : '';
    if (got !== text) {
      console.error(`027 3.2.4: ${t} differs from the regenerated declarations`);
      failed = true;
    }
  } else if (existsSync(dirname(p))) {
    writeFileSync(p, text);
  }
}
if (failed) process.exit(1);
